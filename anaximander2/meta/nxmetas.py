class NxMeta(type):
    """A custom type for Anaximander metaclasses.

    Gotcha: the instances of this class are... metaclasses! This is pushing
    the abstraction of the model to a very unusual extreme and may make it
    difficult to understand right away. However it is worth noting, and
    probably helpful conceptually, that the methods are written using
    the name 'mcl' to refer to instances. For class methods, the designation
    'met' is used to refer to NxMeta itself.
    The method signatures of __new__ and __init__ have been modified to
    incorporate a basename attribute. Basename is a string that is used to
    name types that are programatically generated by instances of NxMeta.
    The namespace passed to NxMeta may contain metacharacters, which
    are then registered in order to customize new type creation.
    """
    basename = 'Nx'
    metacharacters = OrderedDict()

    def __new__(met, name, bases, namespace, basename=None):
        return super().__new__(met, name, bases, namespace)

    def __init__(mcl, name, bases, namespace, basename=None):
        """Initializes a new metaclass."""
        if basename is not None:
            mcl.basename = basename
        # Registers metacharacters
        mcs = OrderedDict(fun.vfilter(fun.typecheck(MetaCharacter), namespace))
        base_regs = (getattr(b, 'metacharacters', {}) for b in bases)
        regs = [mcs] + list(base_regs)
        mcl.metacharacters = OrderedDict()
        for k, v in chain(*[r.items() for r in regs]):
            # We only keep the highest-priority metacharacter version
            # This order is supposed to be consistent with the mro
            if k in mcl.metacharacters:
                continue
            # Check that the attribute assignment is unmodified in mcl
            mcl_value = getattr(mcl, k, None)
            if mcl_value is v:
                mcl.metacharacters[k] = v



class ArchMeta(NxMeta):
    """The [meta-]metaclass for ArcheType.

    Its behaviors are as follows:
    * Sets __archetype__ to None
    * Ensures that the new metaclass has proper __basetype__ and
    __metatype__ attributes. __basetype__ is a declared NxType that
    has been decorated by archetype and will be subclassed to create the
    __archetype__ instance. __metatype__ is the metaclass responsible for
    creating subtypes of the __archetype__. It is normally created by
    nxmeta.
    """

    def __new__(met, name, bases, namespace):
        return type.__new__(met, name, bases, namespace)

    def __init__(mcl, name, bases, namespace):
        # Holds an archetype, the only instance of any ArcheType subclass.
        mcl.__archetype__ = None
        try:
            basetype = namespace['__basetype__']
            metatype = namespace['__metatype__']
            assert isinstance(type(basetype), NxMeta)
            assert isinstance(metatype, NxMeta)
        except (KeyError, AssertionError):
            if name in ('ArcheType', 'ProtoType'):
                return
            msg = "Improper ArchMeta declaration."
            raise TypeError(msg)


# TODO: could make archetype / prototype smarter by allowing metacharacters

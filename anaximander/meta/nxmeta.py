# TODO: add TypeRegistry
class NxMeta(ABCMeta):
    """A custom type for Anaximander metaclasses.

    Gotcha: the instances of this class are... metaclasses! This is pushing
    the abstraction of the model to a very unusual extreme and may make it
    difficult to understand right away. However it is worth noting, and
    probably helpful conceptually, that the methods are written using
    the name 'mcl' to refer to instances. For class methods, the designation
    'met' is used to refer to NxMeta itself.
    The method signatures of __new__ and __init__ have been modified to
    incorporate a basename attribute and optional metadescriptors attribute.
    * basename is a string that is used to name types that are programatically
    generated by instances of NxMeta. In case that a metaclass is
    subclassed by declaration, it will seek a __basename__ declaration in its
    body, or inherit its basename from its parent metaclass.
    * metadescriptors is either None or an iterable of MetaDescriptor
    instances that get called by the __init__ method and may modify the
    namespace of the NxMeta instance accordingly.
    """

    def __new__(met, name, bases, namespace,
                basename=None, metadescriptors=None):
        return type.__new__(met, name, bases, namespace)

    def __init__(mcl, name, bases, namespace,
                 basename=None, metadescriptors=None):
        """Initializes a new metaclass."""
        if basename is not None:
            mcl.__basename__ = basename
        if metadescriptors is not None:
            for md in metadescriptors:
                md(mcl)  # Binds the metadescriptor to the metaclass
        mcl.__counter__ = itertools.count()  # A type counter


def nxmeta(basetype):
    """A metaclass constructor from a supplied archetypical basetype.

    nxmeta creates a metaclass by subclassing the basetype's metaclass
    and modifiying its behavior based on any metadescriptors found
    in the archetype's declarations.
    """
    basename = basetype.__name__
    name = basename + 'Type'
    bases = (type(basetype),)
    try:
        metadescriptors = basetype.__metadescriptors__.values()
    except AttributeError:
        metadescriptors = None
    return NxMeta(name, bases, {}, basename, metadescriptors)

